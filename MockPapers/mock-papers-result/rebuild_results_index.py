"""Rebuild Results_Index.html from every *-Result-Sheet.html in this folder. Re-run after adding a sheet."""
import re, sys, html
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
HERE = Path(__file__).parent
SUBJ = ("Physics", "Chemistry", "Maths")


def strip(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def parse(p):
    t = p.read_text(encoding="utf-8")
    # RT4-Set10-... or a remediation paper RT4-Final-Set-A-... (sorts after the numbered sets)
    m = re.match(r"(\w+?)-(?:Set(\d+)|Final-(?:Set-)?([A-Z]))-", p.name)
    total = re.search(r"<b>([\d.]+)</b><span class=\"of\">/\s*([\d.]+)", t)
    subs = re.findall(r'subj-score">([\d.]+) <small>/ ([\d.]+)', t)
    sub = re.search(r'<p class="sub">(.*?)</p>', t, re.S)
    return dict(mtime=p.stat().st_mtime, file=p.name, exam=m[1], set=(0, int(m[2])) if m[2] else (1, m[3]),
                label=f"Set {m[2]}" if m[2] else f"Final {m[3]}",
                title=strip(re.search(r"<h1>(.*?)</h1>", t, re.S)[1]),
                got=float(total[1]), out=float(total[2]), subs=subs,
                sub=strip(sub[1]) if sub else "")


def n(x):
    return f"{x:g}"


rows = [parse(p) for p in HERE.glob("*-Result-Sheet.html")]
exams = sorted({r["exam"] for r in rows}, key=lambda e: -max(r["mtime"] for r in rows if r["exam"] == e))

out = []
for e in exams:
    sets = sorted((r for r in rows if r["exam"] == e), key=lambda r: r["set"])
    got, tot = sum(r["got"] for r in sets), sum(r["out"] for r in sets)
    out.append(f'<h2>{e[:-1]}-{e[-1]} <span>{len(sets)} set{"s" * (len(sets) > 1)} · average {100 * got / tot:.0f}%</span></h2>')
    out.append('<table><thead><tr><th>Set</th><th>Total</th>' + "".join(f"<th>{s}</th>" for s in SUBJ) + "</tr></thead><tbody>")
    for r in sets:
        pct = 100 * r["got"] / r["out"]
        cells = "".join(f"<td>{a}<small>/{b}</small></td>" for a, b in r["subs"])
        out.append(f'<tr><td><a href="{r["file"]}" target="_blank" rel="noopener">{r["label"]}</a>'
                   f'<span class="d">{html.escape(r["sub"])}</span></td>'
                   f'<td class="t">{n(r["got"])}<small>/{n(r["out"])}</small>'
                   f'<span class="bar"><i style="width:{pct:.0f}%"></i></span></td>{cells}</tr>')
    out.append("</tbody></table>")

page = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Mock Results Index</title>
<style>
  :root{{--paper:#fdfcfa;--rule:#dfe3ea;--ink:#1b2a44;--ink-soft:#5b6a84;--pen:#b7332c;--up:#2f6f57}}
  *{{box-sizing:border-box}}
  body{{margin:0;background:var(--paper);color:var(--ink);font:16px/1.55 "Hoefler Text",Georgia,"Times New Roman",serif;padding:28px 20px 64px}}
  .sheet{{max-width:860px;margin:0 auto}}
  header{{border-bottom:2px solid var(--ink);padding-bottom:14px}}
  h1{{font-size:27px;line-height:1.15;margin:0 0 4px;font-weight:600}}
  .sub{{margin:0;color:var(--ink-soft);font-size:14.5px}}
  h2{{font-size:18px;font-weight:600;margin:34px 0 6px;padding-bottom:6px;border-bottom:1px solid var(--rule)}}
  h2 span{{font-size:13.5px;font-weight:400;color:var(--ink-soft);margin-left:8px}}
  table{{width:100%;border-collapse:collapse;font-size:14.5px}}
  th,td{{text-align:left;padding:8px;border-bottom:1px solid var(--rule);vertical-align:top;font-variant-numeric:tabular-nums}}
  th{{font-size:12.5px;font-weight:600;color:var(--ink-soft);border-bottom:1px solid var(--ink)}}
  td small{{color:var(--ink-soft);font-size:12px}}
  td a{{color:var(--ink);font-weight:600}}
  td .d{{display:block;font-size:12px;color:var(--ink-soft);line-height:1.35;margin-top:2px}}
  td.t{{width:9em;font-weight:600}}
  .bar{{display:block;height:6px;background:#edeff3;margin-top:5px}}
  .bar i{{display:block;height:100%;background:var(--ink)}}
  footer{{margin-top:40px;padding-top:12px;border-top:1px solid var(--rule);font-size:13px;color:var(--ink-soft)}}
  @media (max-width:560px){{body{{padding:20px 14px 48px}} td .d{{display:none}} th,td{{padding:6px 4px;font-size:13.5px}} td.t{{width:auto}}}}
</style>
</head>
<body>
<div class="sheet">
  <header>
    <h1>ICAD Mock Results</h1>
    <p class="sub">{len(rows)} evaluated answer sheets · newest exam first · click a set to open its result sheet</p>
  </header>
  {chr(10).join(out)}
  <footer>Generated by rebuild_results_index.py from the result sheets in this folder. Re-run it after adding a sheet.</footer>
</div>
</body>
</html>
"""
(HERE / "Results_Index.html").write_text(page, encoding="utf-8")
print(f"{len(rows)} sheets, exams: {exams}")
